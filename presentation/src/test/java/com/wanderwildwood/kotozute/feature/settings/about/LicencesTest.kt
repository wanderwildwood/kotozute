package com.wanderwildwood.kotozute.feature.settings.about

import java.io.File
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * The Licenses page's data as the build made it: the AboutLibraries plugin writes
 * build/generated/aboutLibraries/<variant>/res/raw/aboutlibraries.json before the unit tests
 * compile (it is part of the merged resources the R class comes from).
 */
class LicencesTest {
    private val json: File? = File("build/generated/aboutLibraries").walkTopDown()
        .filter { it.name == "aboutlibraries.json" }
        .sortedBy { if ("release" in it.path) 0 else 1 }
        .firstOrNull()

    private val generated by lazy { licenceComponentsFromJson(json!!.readText()) }

    /** What must be on the page whatever else changes: group:artifact, or a config/libraries name. */
    private val EXPECTED = listOf(
        "org.signal:libsignal-android",
        "org.signal:ringrtc-android",
        "io.reactivex.rxjava2:rxjava",
        "com.bluelinelabs:conductor",
        "com.google.dagger:dagger",
        "org.nanohttpd:nanohttpd",
        "com.googlecode.ez-vcard:ez-vcard",
        "androidx.appcompat:appcompat",
        "androidx.core:core",
        "Signal Android service layer",
        "QKSMS",
        "QUIK",
        "InkMessage",
        "android-smsmms",
        "Lato typeface",
        "Java library desugaring (desugar_jdk_libs)",
    )

    @Test fun theBuildListedTheLibraries() {
        assertNotNull("no generated aboutlibraries.json: is the AboutLibraries plugin applied?", json)
        assertTrue(generated.size >= 40)
    }

    @Test fun everyExpectedComponentIsListed() {
        val missing = EXPECTED.filterNot { id -> generated.any { it.note?.startsWith("$id ") == true || it.name == id } }
        assertEquals(emptyList<String>(), missing)
    }

    /** One row per artifact: AndroidX is listed artifact by artifact, never as one "AndroidX" row. */
    @Test fun androidxIsOneRowPerArtifact() {
        val androidx = generated.filter { it.note?.startsWith("androidx.") == true }
        assertTrue(androidx.size >= 5)
        assertEquals(androidx.size, androidx.map { it.note!!.substringBefore(' ') }.toSet().size)
    }

    /** Every row has a full text to show: its own, or a bundled family text. */
    @Test fun everyRowHasAFullText() {
        val rows = Licences.rows("Messaging", generated)
        val bare = rows.filter { it.texts.isEmpty() && it.raws.isEmpty() }.map { "${it.title}: ${it.licence}" }
        assertEquals(emptyList<String>(), bare)
    }

    /** MIT and BSD need the library's own notice: each such row carries its own text, with its copyright line. */
    @Test fun mitAndBsdRowsCarryTheirOwnCopyrightLine() {
        val wanting = generated.filter { c ->
            Licences.families(c.licence).any { it == "mit" || it == "bsd" } &&
                c.texts.none { t -> t.content.orEmpty().contains("Copyright", ignoreCase = true) }
        }.map { "${it.name}: ${it.licence}" }
        assertEquals(emptyList<String>(), wanting)
    }

    @Test fun theListIsTheAppFirstThenEveryComponentAlphabetically() {
        val rows = Licences.rows("Messaging", generated)
        assertTrue(rows.first().isApp)
        assertEquals("Messaging", rows.first().title)
        assertEquals(listOf(Licences.rawsFor(Licences.APP_LICENCE).single()), rows.first().raws)
        val rest = rows.drop(1).map { it.title.lowercase() }
        assertEquals(rest.sorted(), rest)
        assertEquals(rest.size, rest.toSet().size)
    }

    @Test fun agplIsToldApartFromGpl() {
        assertEquals(listOf("agpl"), Licences.families("AGPL-3.0-only"))
        assertEquals(listOf("gpl"), Licences.families("GPL-3.0-or-later"))
        assertEquals(listOf("gpl2-cpe"), Licences.families("GPL-2.0-with-classpath-exception"))
    }

    @Test fun everyBundledTextIsUsed() {
        val used = (Licences.rows("Messaging", generated).flatMap { it.raws }).toSet()
        val unused = Licences.RAW_TEXTS.filter { it.second !in used }.map { it.first }
        assertEquals(emptyList<String>(), unused)
    }

    @Test fun theSourceLinkIsTheRepo() {
        assertEquals("https://github.com/wanderwildwood/kotozute", Licences.SOURCE_URL)
    }

    @Test fun paragraphsSplitOnBlankLines() {
        assertEquals(listOf("a\nb", "c"), Licences.paragraphs("a\nb\n\n \nc\n"))
    }
}
