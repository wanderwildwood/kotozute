/**
 * The icons this app draws, all Material Symbols (Apache-2.0), kept as the path data they
 * ship as rather than transcribed into a builder: an icon is then one line, and adding one is
 * not a chore that invites reusing a wrong icon instead.
 *
 * The same file, with the same path data, is in every app of this shop. It replaced Google's
 * `material-icons-core`/`-extended`, which are a different drawing of the same ideas -- a
 * heavier, rounder cut -- and which were used here in two weights at once. A glyph that
